/* Перенос отредактированных карточек в копии драфта, которые читает runtime.

   node scripts/sync-editorial-steps.mjs --ids id,id[,…] [--write]

   Runtime-оверлей читает шаги не из data/recipe-editorial/cards-*.json, а из
   записей кандидатов (mealprepmanual / goodfood); снимок владельца
   data/owner-reviewed-catalog-corrections.json хранит ещё одну копию кандидата
   и карточки. Скрипт копирует titleRu, paraphrasedInstructionDraft,
   proceduralStatus и proceduralBlockers из карточки ТОЛЬКО для перечисленных
   id и больше ничего не меняет: хранение и упаковку не пересчитывает (в
   отличие от apply-recipe-editorial-cards.mjs --write), порядок ключей и
   форматирование файлов сохраняет. Без --write — только отчёт. Перед записью
   запустите check-editorial-steps.mjs по тем же id. */
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { validateCard } from "./apply-recipe-editorial-cards.mjs";
import {
  EDITORIAL_SYNC_FIELDS,
  OWNER_SNAPSHOT_PATH,
  loadEditorialCandidates,
  loadEditorialCards,
  parseIdList,
  readJson,
  writeJsonPreservingFormat,
} from "./recipe-editorial-steps.mjs";

function changedFields(target, card) {
  return EDITORIAL_SYNC_FIELDS.filter((field) => JSON.stringify(target?.[field]) !== JSON.stringify(card[field]));
}

function describe(target, card, fields) {
  return fields.map((field) => field === "paraphrasedInstructionDraft"
    ? `${field} (${target?.[field]?.length ?? 0} → ${card[field].length} шагов)`
    : field);
}

function copyFields(target, card) {
  // Существующие ключи меняются на месте, поэтому порядок ключей записи не
  // сдвигается; отсутствующий ключ добавляется в конец.
  for (const field of EDITORIAL_SYNC_FIELDS) target[field] = structuredClone(card[field]);
}

export async function syncEditorialSteps({ cwd = process.cwd(), ids, write = false }) {
  if (!ids?.length) throw new Error("Pass --ids id,id to sync edited cards.");
  const [{ entries: cardEntries }, { documents, entries: candidateEntries }, snapshot] = await Promise.all([
    loadEditorialCards(cwd),
    loadEditorialCandidates(cwd),
    readJson(cwd, OWNER_SNAPSHOT_PATH),
  ]);
  if (candidateEntries.length !== cardEntries.length) {
    throw new Error(`Expected one editorial card per candidate; got ${candidateEntries.length}/${cardEntries.length}`);
  }
  const report = [];
  const touched = new Set();
  for (const id of ids) {
    const cardEntry = cardEntries.find((entry) => entry.card.id === id);
    if (!cardEntry) throw new Error(`${id}: no editorial card; simple-home steps are generated by scripts/build-simple-home-candidates.mjs.`);
    const candidateEntry = candidateEntries[cardEntry.order];
    validateCard(cardEntry.card, candidateEntry.candidate);
    const item = { id, card: `${cardEntry.file}#${cardEntry.index}`, updates: [] };
    const candidateFields = changedFields(candidateEntry.candidate, cardEntry.card);
    if (candidateFields.length) {
      item.updates.push({ file: candidateEntry.path, fields: describe(candidateEntry.candidate, cardEntry.card, candidateFields) });
      copyFields(candidateEntry.candidate, cardEntry.card);
      touched.add(candidateEntry.path);
    }
    const snapshotEntry = snapshot.cards.find((entry) => entry.id === id);
    if (snapshotEntry) {
      const snapshotFields = changedFields(snapshotEntry.candidate, cardEntry.card);
      const editorialChanged = JSON.stringify(snapshotEntry.editorial) !== JSON.stringify(cardEntry.card);
      if (snapshotFields.length || editorialChanged) {
        item.updates.push({
          file: OWNER_SNAPSHOT_PATH,
          fields: [
            ...describe(snapshotEntry.candidate, cardEntry.card, snapshotFields).map((field) => `candidate.${field}`),
            ...(editorialChanged ? ["editorial"] : []),
          ],
        });
        copyFields(snapshotEntry.candidate, cardEntry.card);
        snapshotEntry.editorial = structuredClone(cardEntry.card);
        touched.add(OWNER_SNAPSHOT_PATH);
      }
    }
    report.push(item);
  }
  if (write) {
    for (const { path, document } of documents) {
      if (touched.has(path)) await writeJsonPreservingFormat(cwd, path, document);
    }
    if (touched.has(OWNER_SNAPSHOT_PATH)) await writeJsonPreservingFormat(cwd, OWNER_SNAPSHOT_PATH, snapshot);
  }
  return { written: write, files: [...touched], recipes: report };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const argv = process.argv.slice(2);
  const report = await syncEditorialSteps({ ids: parseIdList(argv), write: argv.includes("--write") });
  process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
}
